def hsl(h: float, s: float, l: float) -> str:
    r, g, b = colorsys.hls_to_rgb(h / 360, l, s)
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def rgba(hex_: str, a: float) -> str:
    h = hex_.lstrip("#")
    return f"rgba({int(h[0:2], 16)}, {int(h[2:4], 16)}, {int(h[4:6], 16)}, {a})"


def block(name: str, base: str, hue: float, sat: float, acc: str, deep: str) -> str:
    if base == "dark":
        bg, card, wash = hsl(hue, sat, .035), hsl(hue, sat * .9, .065), hsl(hue, sat * .8, .095)
        ink, ink2, muted = hsl(hue, sat, .95), hsl(hue, sat * .5, .79), hsl(hue, sat * .35, .56)
        on, glow, acc_ink = hsl(hue, sat, .06), .11, acc
    else:
        bg, card, wash = hsl(hue, sat, .972), "#ffffff", hsl(hue, sat * .9, .935)
        ink, ink2, muted = hsl(hue, sat, .10), hsl(hue, sat * .6, .26), hsl(hue, sat * .4, .45)
        on, glow, acc_ink = "#ffffff", .07, deep
    line, line2 = rgba(ink, .10), rgba(ink, .18)
    sel = f':root[data-theme="{base}"][data-palette="{name}"]'
    cool = name in ("indigo", "violet", "pink", "rose", "red", "graphite")
    fx2 = ("#22d3ee" if base == "dark" else "#0891b2") if cool else ("#a78bfa" if base == "dark" else "#7c3aed")
    return f"""{sel} {{
  --fx-1: {acc}; --fx-2: {fx2};
  --bg: {bg}; --bg-2: {card}; --bg-3: {wash}; --ink: {ink}; --ink-2: {ink2}; --muted: {muted};
  --line: {line}; --line-2: {line2}; --green: {acc}; --green-deep: {deep}; --blocked: {acc};
  --paper: {bg}; --card: {card}; --wash: {wash}; --line-strong: {line2}; --faint: {rgba(muted, .75)};
  --brand: {acc}; --brand-ink: {acc_ink}; --brand-wash: {rgba(acc, .13)}; --on-brand: {on}; --link: {acc_ink};
  --surface: {card}; --surface-2: {wash}; --border: {line}; --border-2: {line2}; --text: {ink}; --text-2: {ink2};
  --green-bg: {rgba(acc, .13)}; --blue: {acc_ink};
}}
{sel} body {{ background: radial-gradient(70% 40% at 50% -5%, {rgba(acc, glow)}, transparent 70%), {bg}; background-attachment: fixed; }}
{sel} .brand-mark path:first-child, {sel} .logo svg path:first-child, {sel} .brand svg path:first-child,
{sel} .close-shield svg path:first-child {{ fill: {deep}; stroke: {acc}; }}
{sel} .brand-mark {{ filter: drop-shadow(0 0 14px {rgba(acc, .4)}); }}
"""


