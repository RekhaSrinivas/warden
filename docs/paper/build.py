# --- Table 7 from the lab results ---------------------------------------------------------------

def _pct(x: float) -> str:
    v = round(x * 100, 1)
    return f"{v:g}"


def ablation_table() -> str:
    if not LAB.exists():
        return PLACEHOLDER
    r = json.loads(LAB.read_text(encoding="utf-8"))
    rows = ["| Design | Red team: paid (95% CI) | held | blocked | Legitimate paid | "
            "Scripted attacks: paid / held / blocked | Scripted clean paid |",
            "|---|---|---|---|---|---|---|"]
    for d in r["designs"]:
        res = r["results"].get(d["id"])
        if res is None:
            continue
        s, sc = res["summary"], res.get("scripted", {}).get("summary", {})
        lo, hi = s["paid_rate_ci95"]
        scripted = f"{sc['paid']} / {sc['held']} / {sc['blocked']}" if sc else "n/a"
        clean = f"{sc['clean_paid']}/{sc['clean']}" if sc else "n/a"
        rows.append(f"| {d['id']} {d['name']} | {s['paid']}/{s['attacks']} ({_pct(lo)}–{_pct(hi)}%) | {s['held']} | "
                    f"{s['blocked']} | {s['legit_paid']}/{s['legitimate']} | {scripted} | {clean} |")
    print(f"Table 7 refreshed from {LAB.relative_to(ROOT)} (scored {r.get('scored_at')}). "
          "Check that the prose in Section 4.6 still matches it.")
    return "\n".join(rows)


def refresh_ablation(md: str) -> str:
    table = ablation_table()
    if START in md and END in md:
        before, rest = md.split(START, 1)
        _, after = rest.split(END, 1)
        return f"{before}{START}\n{table}\n{END}{after}"
    if "<!-- ABLATION TABLE: fill from docs/lab/results.json -->" in md and LAB.exists():
        return md.replace("<!-- ABLATION TABLE: fill from docs/lab/results.json -->", f"{START}\n{table}\n{END}", 1)
    return md


# --- a small Markdown subset -> HTML ---------------------------------------------------------------

def inline(text: str) -> str:
    codes: list[str] = []

    def keep(m: re.Match[str]) -> str:
        codes.append(f"<code>{html.escape(m.group(1))}</code>")
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", keep, text)
    text = html.escape(text, quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', text)
    text = text.replace(" -- ", " – ")
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], text)


def table(lines: list[str]) -> str:
    def cells(line: str) -> list[str]:
        return [c.strip() for c in line.strip().strip("|").split("|")]

    head, body = cells(lines[0]), [cells(l) for l in lines[2:]]
    out = ["<table>", "<thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead>", "<tbody>"]
    out += ["<tr>" + "".join(f"<td>{inline(c)}</td>" for c in row) + "</tr>" for row in body]
    return "\n".join(out + ["</tbody>", "</table>"])


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def convert(md: str) -> tuple[dict[str, str], str]:
    meta: dict[str, str] = {}
    if md.startswith("---"):
        _, front, md = md.split("---", 2)
        for line in front.strip().splitlines():
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip().strip('"')

    lines = md.strip().splitlines()
    out: list[str] = []
    i, section = 0, None
    pending_caption: str | None = None

    def close_section() -> None:
        if section:
            out.append("</section>")

    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        if line.startswith("```"):
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append("<pre><code>" + html.escape("\n".join(lines[i + 1:j])) + "</code></pre>")
            i = j + 1
            continue
        if line.startswith("<!--"):
            j = i
            while "-->" not in lines[j]:
                j += 1
            out.append("\n".join(lines[i:j + 1]))
            i = j + 1
            continue
        m = re.match(r"^(#{2,4})\s+(.*)$", line)
        if m:
            level, title = len(m.group(1)), m.group(2).strip()
            if level == 2:
                close_section()
                section = slug(title)
                cls = "abstract" if title.lower() == "abstract" else ("artifact" if title.lower().startswith("artifact") else "")
                out.append(f'<section id="{section}" class="{cls}">')
            out.append(f'<h{level} id="{slug(title)}">{inline(title)}</h{level}>')
            i += 1
            continue
        if line.startswith("|"):
            j = i
            while j < len(lines) and lines[j].startswith("|"):
                j += 1
            cap = f'<figcaption>{inline(pending_caption)}</figcaption>' if pending_caption else ""
            wide = " wide" if len(lines[i].split("|")) > 6 else ""
            wide += " short" if j - i <= 9 else ""
            out.append(f'<figure class="tbl{wide}">{cap}{table(lines[i:j])}</figure>')
            pending_caption = None
            i = j
            continue
        if re.match(r"^(-|\d+\.)\s", line):
            ordered = bool(re.match(r"^\d+\.", line))
            items: list[str] = []
            while i < len(lines) and lines[i].strip():
                if re.match(r"^(-|\d+\.)\s", lines[i]):
                    items.append(re.sub(r"^(-|\d+\.)\s+", "", lines[i]))
                else:
                    items[-1] += " " + lines[i].strip()
                i += 1
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(t)}</li>" for t in items) + f"</{tag}>")
            continue
        j = i
        para = []
        while j < len(lines) and lines[j].strip() and not re.match(r"^(#|\||```|<!--|-\s|\d+\.\s)", lines[j]):
            para.append(lines[j].strip())
            j += 1
        text = " ".join(para)
        i = j
        if re.match(r"^Table \d+\.", text):
            pending_caption = text
            continue
        if text.startswith("Warden doesn't ask you to trust"):
            out.append(f'<p class="closing">{inline(text)}</p>')
        else:
            out.append(f"<p>{inline(text)}</p>")
    close_section()
    return meta, "\n".join(out)


