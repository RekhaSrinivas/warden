# --- PDF -------------------------------------------------------------------------------------------

def find_browser() -> str | None:
    for b in BROWSERS:
        if Path(b).exists():
            return b
        found = shutil.which(b)
        if found:
            return found
    return None


def print_pdf(html_path: Path, pdf_path: Path) -> None:
    browser = find_browser()
    if browser is None:
        raise SystemExit("No Edge or Chrome found; open the HTML and print it to PDF by hand.")
    if pdf_path.exists():
        pdf_path.unlink()
    with tempfile.TemporaryDirectory() as profile:
        cmd = [browser, "--headless=new", "--disable-gpu", "--no-first-run", "--no-default-browser-check",
               f"--user-data-dir={profile}", "--no-pdf-header-footer", "--run-all-compositor-stages-before-draw",
               f"--print-to-pdf={pdf_path}", html_path.resolve().as_uri()]
        subprocess.run(cmd, check=False, timeout=120, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if not pdf_path.exists() or pdf_path.stat().st_size < 10_000:
        raise SystemExit(f"PDF was not written correctly by {browser}")
    pages = "?"
    try:
        from pypdf import PdfReader
        pages = str(len(PdfReader(str(pdf_path)).pages))
    except Exception:  # pypdf is optional
        pass
    print(f"Wrote {pdf_path} ({pdf_path.stat().st_size:,} bytes, {pages} pages) with {Path(browser).name}")


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--no-pdf", action="store_true")
    args = parser.parse_args()

    md = MD.read_text(encoding="utf-8")
    refreshed = refresh_ablation(md)
    if refreshed != md:
        MD.write_text(refreshed, encoding="utf-8")
        print(f"Updated Table 7 in {MD.name}")
    if "ABLATION TABLE: fill from" in refreshed:
        print("Note: the ablation placeholder is still in the report (docs/lab/results.json not found).")
    meta, body = convert(refreshed)
    HTML_OUT.write_text(render(meta, body), encoding="utf-8")
    print(f"Wrote {HTML_OUT}")
    if not args.no_pdf:
        print_pdf(HTML_OUT, PDF_OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
